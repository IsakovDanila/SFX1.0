def normalize_key(key: str) -> str:
    """'Glass Breaking' / 'glass-breaking' / 'glass_breaking' -> 'glass_breaking'."""
    k = (key or "").strip().lower().replace("-", "_").replace(" ", "_")
    while "__" in k:
        k = k.replace("__", "_")
    return ALIASES.get(k, k)


def ru_name(key: str) -> str:
    """Русское название категории. Для неизвестных ключей — ключ как есть."""
    entry = RU_LABELS.get(normalize_key(key))
    return entry["ru"] if entry else (key or "")


def ru_tags(key: str, limit: int = 6) -> list[str]:
    """Русские теги категории (главная метка + синонимы).

    Для неизвестной категории — разбиваем английский ключ на слова, чтобы
    поиск хотя бы по имени класса продолжал работать.
    """
    entry = RU_LABELS.get(normalize_key(key))
    if entry:
        return entry["tags"][:limit]
    return [w for w in (key or "").replace("-", "_").split("_") if w][:limit]


def is_known(key: str) -> bool:
    return normalize_key(key) in RU_LABELS


def all_keys() -> list[str]:
    return sorted(RU_LABELS)


